#!/usr/bin/env node
/**
 * Generate the `word_bank` seed from the curated wordlists.
 *
 * `word_bank` holds ANSWERS ONLY. The much larger guess lists stay out of the
 * database entirely: they ship to the browser as static JSON so the client can
 * check spelling offline, while the server keeps the answers. Seeding guesses
 * here would put 47,000 rows in a table whose whole point is to be unreadable.
 *
 *   node supabase/scripts/seed-word-bank.mjs            # -> supabase/seed.sql
 *   node supabase/scripts/seed-word-bank.mjs --check    # validate, write nothing
 *   node supabase/scripts/seed-word-bank.mjs --out path
 *
 * `supabase db reset` picks up supabase/seed.sql automatically. Against a remote
 * project: psql "$SUPABASE_DB_URL" -f supabase/seed.sql
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '../..')

const SOURCE = join(repoRoot, 'docs/wordlists/wordlists.json')
const MODES = [5, 6, 7]
const ROWS_PER_STATEMENT = 500

const args = process.argv.slice(2)
const checkOnly = args.includes('--check')
const outIndex = args.indexOf('--out')
const outPath =
  outIndex !== -1 && args[outIndex + 1]
    ? resolve(process.cwd(), args[outIndex + 1])
    : join(repoRoot, 'supabase/seed.sql')

/** @param {string} word @param {number} len */
function isValid(word, len) {
  return typeof word === 'string' && word.length === len && /^[a-z]+$/.test(word)
}

function collect() {
  /** @type {{ word: string; len: number; rank: number }[]} */
  const rows = []
  /** @type {string[]} */
  const problems = []

  const raw = JSON.parse(readFileSync(SOURCE, 'utf8'))

  for (const len of MODES) {
    const answers = raw[String(len)]?.answers
    if (!Array.isArray(answers) || answers.length === 0) {
      problems.push(`${len}-letter: no answers array in ${SOURCE}`)
      continue
    }

    const seen = new Set()
    let rank = 0

    for (const entry of answers) {
      const word = String(entry).trim().toLowerCase()
      if (!isValid(word, len)) {
        problems.push(`${len}-letter: rejected ${JSON.stringify(entry)}`)
        continue
      }
      if (seen.has(word)) continue
      seen.add(word)
      rank += 1
      rows.push({ word, len, rank })
    }
  }

  return { rows, problems }
}

function toSql(rows) {
  const header = [
    '-- Generated by supabase/scripts/seed-word-bank.mjs. Do not edit by hand.',
    `-- Source: docs/wordlists/wordlists.json (${rows.length} answers)`,
    '',
    'begin;',
    '',
    'truncate table public.word_bank;',
    '',
  ]

  const statements = []
  for (let i = 0; i < rows.length; i += ROWS_PER_STATEMENT) {
    const chunk = rows.slice(i, i + ROWS_PER_STATEMENT)
    const values = chunk.map((r) => `  ('${r.word}', ${r.len}, ${r.rank})`).join(',\n')
    statements.push(`insert into public.word_bank (word, len, rank) values\n${values};\n`)
  }

  return [...header, ...statements, 'commit;', ''].join('\n')
}

const { rows, problems } = collect()

for (const problem of problems) {
  console.error(`warn: ${problem}`)
}

if (rows.length === 0) {
  console.error('error: no answers collected; refusing to write an empty seed')
  process.exit(1)
}

const counts = MODES.map((len) => `${len}: ${rows.filter((r) => r.len === len).length}`).join('  ')

if (checkOnly) {
  console.error(`ok: ${rows.length} answers (${counts}), ${problems.length} rejected`)
  process.exit(0)
}

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, toSql(rows), 'utf8')
console.error(`wrote ${outPath}: ${rows.length} answers (${counts})`)
