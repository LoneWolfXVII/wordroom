#!/usr/bin/env node
/**
 * Generate the `guess_bank` seed — the server's spelling dictionary.
 *
 * Separate from the word-bank seed because the two tables answer different
 * questions and have different secrecy: `word_bank` holds answers and no client
 * may read it, `guess_bank` holds the ~47,000 guessable words and is merely
 * unnecessary for a client to ask about.
 *
 * Emitted as one `unnest(string_to_array(...))` per length rather than 47,000
 * VALUES rows: about a third of the bytes, and three statements instead of
 * ninety-four, which matters when it has to go through a browser SQL editor.
 *
 *   node supabase/scripts/seed-guess-bank.mjs         # -> supabase/seed-guesses.sql
 *   node supabase/scripts/seed-guess-bank.mjs --check
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '../..')
const SOURCE = join(repoRoot, 'docs/wordlists/wordlists.json')
const OUT = join(repoRoot, 'supabase/seed-guesses.sql')
const MODES = [5, 6, 7]

const checkOnly = process.argv.includes('--check')
const raw = JSON.parse(readFileSync(SOURCE, 'utf8'))

const byLen = new Map()
let rejected = 0

for (const len of MODES) {
  const entry = raw[String(len)] ?? {}
  // Answers are guessable too — a player must be able to type the solution.
  const words = new Set()
  for (const list of [entry.guesses ?? [], entry.answers ?? []]) {
    for (const value of list) {
      const word = String(value).trim().toLowerCase()
      if (word.length !== len || !/^[a-z]+$/.test(word)) {
        rejected += 1
        continue
      }
      words.add(word)
    }
  }
  byLen.set(len, [...words].sort())
}

const total = [...byLen.values()].reduce((sum, list) => sum + list.length, 0)
const counts = MODES.map((len) => `${len}: ${byLen.get(len).length}`).join('  ')

/*
 * The invariants the dictionary has to hold, checked here because there is no
 * longer a module to unit-test: the list has to accept every word a player
 * could legitimately type — every possible *answer* above all, since being
 * unable to type the solution would be unplayable — and it has to be big enough
 * to be a real dictionary rather than a truncated file.
 */
const problems = []
for (const len of MODES) {
  const words = new Set(byLen.get(len))
  if (words.size < 5_000) {
    problems.push(`${len}-letter list is only ${words.size} words`)
  }
  for (const answer of raw[String(len)]?.answers ?? []) {
    const word = String(answer).trim().toLowerCase()
    if (!words.has(word)) problems.push(`${len}-letter answer "${word}" is not guessable`)
  }
}

if (problems.length > 0) {
  for (const problem of problems.slice(0, 10)) console.error(`error: ${problem}`)
  console.error(`error: ${problems.length} problem(s); refusing to write the seed`)
  process.exit(1)
}

if (total === 0) {
  console.error('error: no guesses collected; refusing to write an empty seed')
  process.exit(1)
}

if (checkOnly) {
  console.error(`ok: ${total} guessable words (${counts}), ${rejected} rejected`)
  process.exit(0)
}

const parts = [
  '-- Generated by supabase/scripts/seed-guess-bank.mjs. Do not edit by hand.',
  `-- Source: docs/wordlists/wordlists.json (${total} words)`,
  '',
  'begin;',
  '',
  'truncate table public.guess_bank;',
  '',
]

for (const len of MODES) {
  parts.push(
    `insert into public.guess_bank (word, len)\nselect word, ${len}\n  from unnest(string_to_array('${byLen.get(len).join(',')}', ',')) as word;\n`,
  )
}

parts.push('commit;', '')
writeFileSync(OUT, parts.join('\n'), 'utf8')
console.error(`wrote ${OUT}: ${total} words (${counts})`)
